import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import test from 'node:test';
import { renderControlCenter } from '../apps/local-agent/src/control-center.ts';

const read = async (name:string) => fs.readFile(new URL('../' + name, import.meta.url), 'utf8');

test('C10 troubleshooting covers six owner-relevant blocked paths, without claiming recovery authority', async () => {
  const [shell, style] = await Promise.all([
    read('apps/control-center/src/shell.html'),
    read('apps/control-center/src/styles.css')
  ]);
  const start = shell.indexOf('<section class="supportGuide"');
  const end = shell.indexOf('</section>', start);
  assert.ok(start > 0 && end > start);
  const guide = shell.slice(start, end + 10);
  assert.equal((guide.match(/<details>/g) ?? []).length, 6);
  for (const phrase of [
    'Install or doctor reports a problem',
    'Agent already running',
    'Locked, blocked or uncertain recovery',
    'Pairing or local browser sign-in fails',
    'Device is offline',
    'Approval expired or timed out'
  ]) assert.ok(guide.includes(phrase), phrase);
  assert.ok(guide.includes('Keep original receipts quarantined'));
  assert.ok(guide.includes('Browser sign-in alone never approves an action'));
  assert.ok(guide.includes('Never share bearer tokens'));
  assert.doesNotMatch(guide, /<button\b|<script\b|onclick=|onerror=|onload=|localStorage|sessionStorage/i);
  assert.match(style, /\.supportGuide summary:focus-visible\{/);
  assert.match(guide, /aria-labelledby="supportGuideTitle"/);
});
test('C10 generated Control Center is exact source build with safely replaced nonce', async () => {
  const [shell,style,app,actual] = await Promise.all([
    read('apps/control-center/src/shell.html'),
    read('apps/control-center/src/styles.css'),
    read('apps/control-center/src/app.js'),
    read('apps/local-agent/src/control-center.ts')
  ]);
  // Git checkout line endings vary by OS; the canonical builder normalizes inputs.
  const normalize = (input: string) => input.replace(/\r\n?/g, '\n');
  const template = normalize(shell).replace('__MECORD_STYLE__', normalize(style).trim())
    .replace('__MECORD_SCRIPT__', normalize(app).trim());
  const generated = '// GENERATED by apps/control-center/scripts/build.mjs. Edit apps/control-center/src/* instead.\n' +
    'const CONTROL_CENTER_TEMPLATE = ' + JSON.stringify(template) + ';\n\n' +
    'export function renderControlCenter(nonce: string): string {\n' +
    "  const safeNonce = nonce.replace(/[^A-Za-z0-9_-]/g, '');\n" +
    "  return CONTROL_CENTER_TEMPLATE.replaceAll('__MECORD_NONCE__', safeNonce);\n" +
    '}\n';
  // Git's Windows checkout may normalize LF to CRLF; compare logical generated bytes.
  assert.equal(actual.replace(/\r\n/g, '\n'), generated.replace(/\r\n/g, '\n'));
  const html = renderControlCenter('safe_nonce!bad');
  assert.match(html, /nonce="safe_noncebad"/);
  assert.ok(html.includes('Safe troubleshooting'));
  assert.ok(html.includes('role="tablist"'));
  assert.ok(html.includes('aria-live="polite"'));
  assert.ok(!html.includes('__MECORD_STYLE__'));
  assert.ok(!html.includes('__MECORD_SCRIPT__'));
});
